import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const sourceRoot = path.resolve(process.argv[2] || "../photos");
const projectRoot = path.resolve(import.meta.dirname, "..");
const publicRoot = path.join(projectRoot, "public", "photos");
const manifestPath = path.join(projectRoot, "app", "photo-manifest.ts");

const cityFolders = {
  "东京": { slug: "tokyo", mapCity: "Tokyo", local: "东京", country: "Japan", countryLocal: "日本" },
  "伊斯坦布尔": { slug: "istanbul", mapCity: "Istanbul", local: "伊斯坦布尔", country: "Türkiye", countryLocal: "土耳其" },
  "大阪": { slug: "osaka", mapCity: "Osaka", local: "大阪", country: "Japan", countryLocal: "日本" },
  "新疆": { slug: "altay", mapCity: "Altay", local: "阿勒泰 · 新疆", country: "China", countryLocal: "中国" },
  "马来西亚": { slug: "tawau", mapCity: "Tawau", local: "仙本那", country: "Malaysia", countryLocal: "马来西亚" },
  "Tokyo": { slug: "tokyo", mapCity: "Tokyo", local: "东京", country: "Japan", countryLocal: "日本" },
  "Istanbul": { slug: "istanbul", mapCity: "Istanbul", local: "伊斯坦布尔", country: "Türkiye", countryLocal: "土耳其" },
  "Osaka": { slug: "osaka", mapCity: "Osaka", local: "大阪", country: "Japan", countryLocal: "日本" },
  "Semporna": { slug: "tawau", mapCity: "Tawau", local: "仙本那", country: "Malaysia", countryLocal: "马来西亚" },
  "Shenzhen": { slug: "shenzhen", mapCity: "Shenzhen", local: "深圳", country: "China", countryLocal: "中国" },
};

const isPhoto = (name) => /\.(jpe?g|png|webp|heic)$/i.test(name);
const folders = (await fs.readdir(sourceRoot, { withFileTypes: true })).filter((entry) => entry.isDirectory());
const albums = [];

for (const folder of folders) {
  const city = cityFolders[folder.name];
  if (!city) {
    console.warn(`Skipping unmatched photo folder: ${folder.name}`);
    continue;
  }

  const sourceDir = path.join(sourceRoot, folder.name);
  const targetDir = path.join(publicRoot, city.slug);
  const files = (await fs.readdir(sourceDir))
    .filter(isPhoto)
    .sort((a, b) => a.localeCompare(b, "zh-CN", { numeric: true }));
  const coverName = files.find((file) => /^cover\./i.test(file));
  if (!coverName) throw new Error(`${folder.name} is missing cover.jpg`);

  await fs.rm(targetDir, { recursive: true, force: true });
  await fs.mkdir(targetDir, { recursive: true });

  const ordered = [coverName, ...files.filter((file) => file !== coverName)];
  const outputPhotos = [];
  for (let index = 0; index < ordered.length; index += 1) {
    const source = path.join(sourceDir, ordered[index]);
    const outputName = index === 0 ? "cover.webp" : `${String(index).padStart(2, "0")}.webp`;
    const output = path.join(targetDir, outputName);
    await sharp(source)
      .rotate()
      .resize({
        width: index === 0 ? 2400 : 1800,
        height: index === 0 ? 2400 : 1800,
        fit: "inside",
        withoutEnlargement: true,
      })
      .webp({ quality: index === 0 ? 84 : 80, effort: 5 })
      .toFile(output);
    outputPhotos.push(`photos/${city.slug}/${outputName}`);
  }

  albums.push({
    ...city,
    hero: outputPhotos[0],
    photos: outputPhotos.slice(1),
    story: "AI Story 正在构思中。未来这里将根据你的照片与旅程，生成只属于这座城市的摄影记忆。",
  });
}

albums.sort((a, b) => a.slug.localeCompare(b.slug));
const manifest = `// Generated by scripts/sync-photo-library.mjs. Do not edit by hand.
export type PhotoAlbum = {
  slug: string;
  mapCity: string;
  local: string;
  country: string;
  countryLocal: string;
  hero: string;
  photos: string[];
  story: string;
};

export const photoAlbums: PhotoAlbum[] = ${JSON.stringify(albums, null, 2)};

export const photoAlbumsBySlug = new Map(photoAlbums.map((album) => [album.slug, album]));
export const photoAlbumsByCity = new Map(photoAlbums.map((album) => [album.mapCity, album]));
`;

await fs.writeFile(manifestPath, manifest);
console.log(`Generated ${albums.length} albums from ${sourceRoot}`);
